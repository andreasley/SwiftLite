import SwiftSyntax
import SwiftSyntaxBuilder
import SwiftSyntaxMacros
import SwiftDiagnostics

public struct ModelMacro: MemberMacro, ExtensionMacro
{
    public static func expansion(of node: SwiftSyntax.AttributeSyntax, attachedTo declaration: some SwiftSyntax.DeclGroupSyntax, providingExtensionsOf type: some SwiftSyntax.TypeSyntaxProtocol, conformingTo protocols: [SwiftSyntax.TypeSyntax], in context: some SwiftSyntaxMacros.MacroExpansionContext) throws -> [SwiftSyntax.ExtensionDeclSyntax]
    {
        var generatedExtensions = [SwiftSyntax.ExtensionDeclSyntax]()
        
        // MARK: FetchableObject
        
        let proto: TypeSyntax = "SwiftLite.FetchableObject"

        // If the type already claims the conformance, skip emitting another extension
        if !protocols.contains(where: { $0.trimmedDescription == proto.trimmedDescription }) {
            if let fetchableExtensionDecl = ExtensionDeclSyntax(DeclSyntax(stringLiteral: "extension \(type): \(proto) {}")) {
                generatedExtensions.append(fetchableExtensionDecl)
            }
        }

        return generatedExtensions
    }
    
    enum ModelFixItMessage: String, FixItMessage {
        case removeDefaultValue

        var message: String {
            switch self {
            case .removeDefaultValue:
                "Remove default value."
            }
        }

        var fixItID: MessageID {
            MessageID(domain: "ModelMacro", id: self.rawValue)
        }
    }
    
    enum ErrorMessage: String, DiagnosticMessage {
        case duplicateInitializer
        case notAClass
        case unexpectedPropertyDefaultValue
        case unexpectedMultipleBindings
        case unexpectedBindingPattern
        case failedToFindType
        case failedToGenerateTableName
        case failedToGenerateColumnName

        var message: String {
            switch self {
            case .duplicateInitializer:
                "SwiftLite Models aren't allowed to have a custom default initializer. Use convenience initializers instead."
            case .notAClass:
                "SwiftLite Model must be a class."
            case .unexpectedPropertyDefaultValue:
                "Properties in a SwiftLite Model must not have a default value. Annotate the property with `@Default()` or use a convenience initializer."
            case .unexpectedMultipleBindings:
                "Properties in a SwiftLite Model must not have multiple bindings."
            case .unexpectedBindingPattern:
                "Properties in a SwiftLite Model must define the name of a single variable."
            case .failedToFindType:
                "Properties in a SwiftLite Model must have a type specified."
            case .failedToGenerateTableName:
                "Failed to generate table name from class name."
            case .failedToGenerateColumnName:
                "Failed to generate column name from property name."
            }
        }
        
        var diagnosticID: MessageID {
            MessageID(domain: "ModelMacro", id: self.rawValue)
        }
        
        var severity: DiagnosticSeverity {
            .error
        }
    }

    public static func expansion(of node: AttributeSyntax, providingMembersOf declaration: some DeclGroupSyntax, in context: some MacroExpansionContext) throws -> [DeclSyntax]
    {
        var diagnostics: [Diagnostic] = []
        var generatedDeclarations: [DeclSyntax] = []

        // MARK: Check object type
        // Check if the annotated object is a `class` (which is the only supported nominal type)

        let classDecl = declaration.as(ClassDeclSyntax.self)
        if classDecl == nil {
            diagnostics.append(Diagnostic(node: declaration, message: ErrorMessage.notAClass))
        }
        
        // TODO: Check if the class is `final`, which is required because of the autogenerated conformance to the `FetchableObject` protocol which has a `Self` constraint on its `entity`. This in turn is necessary to in the future have KeyPaths in its `properties`.
        
        // MARK: Generate table name

        var tableName: String?
        if let classDecl {
            // TODO: Check if there's already a `static let tableName: String`. If so, that should be used instead of a generated one.
            do {
                tableName = try createTableNameFromQualifiedName(of: classDecl, in: context)
            } catch {
                diagnostics.append(Diagnostic(node: declaration, message: ErrorMessage.failedToGenerateTableName))
                // TODO: Add FixIt to add manual table name.
            }
        }

        // MARK: Table name
        if let tableName {
            let memberDecl: DeclSyntax =
            """
            static let tableName = "\(raw: tableName)"
            """
            generatedDeclarations.append(memberDecl)
        }

        
        // MARK: ID

        let idDecl: DeclSyntax =
        """
        let id: UUID
        """
        generatedDeclarations.append(idDecl)


        // TODO: Iterate properties only once


        // MARK: Entity
        // The entity details are required in the compiled app to check the schema and execute migrations if necessary.

        var propertyNames: [String] = []
        var properties = [ModelConfiguration.Property]()
        
        properties.append(ModelConfiguration.Property(name: "id", columnName: "id", type: "UUID", isPrimaryKey: true, isUnique: false, isIndexed: false, defaultValue: nil))
        
        for member in declaration.memberBlock.members {
            
            // only the first variable binding is relevant here
            guard let varDecl = member.decl.as(VariableDeclSyntax.self) else { continue }
            guard let firstBinding = varDecl.bindings.first else { continue }
            
            // static properties are ignored
            guard !varDecl.isStatic else { continue }

            // currently, only a single binding is supported
            guard varDecl.bindings.count == 1 else {
                let diag = Diagnostic(node: varDecl, message: ErrorMessage.unexpectedMultipleBindings)
                diagnostics.append(diag)
                continue
            }

            // only identifier patterns are supported (e.g. no tuple patterns)
            guard let identifierPattern = firstBinding.pattern.as(IdentifierPatternSyntax.self) else {
                let diag = Diagnostic(node: varDecl, message: ErrorMessage.unexpectedBindingPattern)
                diagnostics.append(diag)
                continue
            }
            
            guard let type = firstBinding.typeAnnotation?.type else {
                let diag = Diagnostic(node: varDecl, message: ErrorMessage.failedToFindType)
                diagnostics.append(diag)
                continue
            }

            
            let name = identifierPattern.identifier.text

            propertyNames.append(name)
            do {
                var isUnique = false
                var isIndexed = false
                var defaultValue: ExprSyntax?

                for attribute in varDecl.attributes {
                    guard let attrId = attribute.as(AttributeSyntax.self)?.attributeName.as(IdentifierTypeSyntax.self) else { continue }
                    switch attrId.name.text {
                        case "Unique":
                        isUnique = true
                    case "Indexed":
                        isIndexed = true
                    case "DefaultValue":
                        if case let .attribute(attr) = attribute, let arguments = attr.arguments, case let .argumentList(argList) = arguments, let expressionOfFirstArgument = argList.first?.expression {
                            let defaultValuePropertyName = "__defaultValue_\(name)"
                            let defaultValueDecl: DeclSyntax =
                            """
                            private static let \(raw: defaultValuePropertyName): \(firstBinding.typeAnnotation?.type) = \(expressionOfFirstArgument)
                            """
                            generatedDeclarations.append(defaultValueDecl)
                            defaultValue = .init(stringLiteral: defaultValuePropertyName)
                        }
                    default:
                        break
                    }
                }

                let columnName = try SQLiteHelpers.generateIdentifierName([name])
                properties.append(.init(name: name, columnName: columnName, type: type, isPrimaryKey: false, isUnique: isUnique, isIndexed: isIndexed, defaultValue: defaultValue))
            } catch {
                // TODO: Differentiate the errors if there are multiple `try`
                let diag = Diagnostic(node: varDecl, message: ErrorMessage.failedToGenerateColumnName)
                diagnostics.append(diag)
            }

            // Initial values for properties aren't supported in SwiftLite, because they make it impossible to set the value for `let` properties in the initializer (which is what is required when initializing a model from database results)
            // Check if the binding has an initializer and show an error if so, because default initializers aren't supported in SwiftLite
            if let initializer = firstBinding.initializer {
                // TODO: Change FixIt to move the value to a @Default() Macro instead of just deleting the initializer
                let fixIt = FixIt(
                    message: ModelFixItMessage.removeDefaultValue,
                    changes: [
                        FixIt.Change.replace(
                            oldNode: Syntax(initializer),
                            newNode: Syntax(TokenSyntax(stringLiteral: ""))
                        )
                    ]
                )

                let diag = Diagnostic(node: varDecl, message: ErrorMessage.unexpectedPropertyDefaultValue, fixIt: fixIt)
                diagnostics.append(diag)
            }
        }


        var hasEntity = false
        if let classDecl, let tableName {
            // Build the property initializers dynamically
            let propertyDecls: [String] = properties.map { p in
                """
                .init(name: "\(p.name)", columnName: "\(p.columnName)", type: \(p.type).self, isPrimaryKey: \(p.isPrimaryKey), isUnique: \(p.isUnique), isIndexed: \(p.isIndexed), isNullable: \(p.typeIsOptional))
                """
            }

            // Join them with commas/newlines
            let propertiesBlock = propertyDecls.joined(separator: ",\n")

            // Build the final DeclSyntax
            let entityDecl: DeclSyntax =
            """
            static let entity = Schema.Entity<\(raw: classDecl.name)>(name: "\(classDecl.name)", tableName: "\(raw: tableName)", properties: [
                \(raw: propertiesBlock)
            ])
            """
            generatedDeclarations.append(entityDecl)
            hasEntity = true
        }


        // MARK: Entity registration

        if hasEntity {
            let entityRegistrationDecl: DeclSyntax =
            """
            private static let __schemaRegistration: Void = {
                Schema.default.register(entity)
            }()
            """
            generatedDeclarations.append(entityRegistrationDecl)
            
            // MARK: Throw errors if there were some
            
            if diagnostics.count > 0 {
                throw DiagnosticsError(diagnostics: diagnostics)
            }
        }
        
        // MARK: Initializer
        
        // Check if there's already an initializer. If so, throw (because it's necessary to generate the required initializers to properly handle read-only fields and the `id` property.
        if let initMember = declaration.memberBlock.members.first(where: { member in
            guard let initDecl = member.decl.as(InitializerDeclSyntax.self) else { return false }
            return !initDecl.modifiers.contains(where: { $0.name.text == "convenience" })
        }) {
            let diag = Diagnostic(node: initMember.decl, message: ErrorMessage.duplicateInitializer)
            diagnostics.append(diag)
        }

        // Generate initializer
        let parameters: [FunctionParameterSyntax] = declaration.memberBlock.members.compactMap { member in
            guard let variable = member.decl.as(VariableDeclSyntax.self),
                  let binding = variable.bindings.first,
                  let identifier = binding.pattern.as(IdentifierPatternSyntax.self),
                  !variable.isStatic
            else { return nil }
            
            let name = identifier.identifier.text
            let type = binding.typeAnnotation?.type.description.trimmingCharacters(in: .whitespacesAndNewlines) ?? "Any"
            let isOptional = type.hasSuffix("?")
            
            let defaultValue: InitializerClauseSyntax?
            if let defaultValueFromAttribute = properties.first(where: { $0.name == name })?.defaultValue {
                defaultValue = InitializerClauseSyntax(value: defaultValueFromAttribute)
            } else if isOptional {
                defaultValue = InitializerClauseSyntax(value: ExprSyntax("nil"))
            } else {
                defaultValue = nil
            }
            
            return FunctionParameterSyntax(
                firstName: .identifier(name),
                colon: .colonToken(trailingTrivia: .space),
                type: TypeSyntax(stringLiteral: type),
                defaultValue: defaultValue
            )
        }
        
        let parameterList = FunctionParameterClauseSyntax { parameters }
        
        let idAssignment = CodeBlockItemSyntax(item: .expr("self.id = UUID()"))
        var assignments: [CodeBlockItemSyntax] = [idAssignment]

        for parameter in parameters {
            let name = parameter.firstName.text
            let assignment = CodeBlockItemSyntax(item: .expr("self.\(raw: name) = \(raw: name)"))
            assignments.append(assignment)
        }
        
        let initDecl = InitializerDeclSyntax(
            modifiers: [DeclModifierSyntax(name: .keyword(.public))],
            signature: FunctionSignatureSyntax(parameterClause: parameterList),
            body: CodeBlockSyntax(statements: CodeBlockItemListSyntax(assignments))
        )
        
        generatedDeclarations.append(DeclSyntax(initDecl))

        // Note: The SQL `CREATE TABLE` statement is not generated by the Macro. While it would be great to be able to inspect it right in the IDE by expanding the Macro, generating it here is not possible because the Macro operates on syntax only (but needs type information to create a proper `CREATE TABLE`).

        return generatedDeclarations
    }

    static func createTableNameFromQualifiedName(of declaration: ClassDeclSyntax, in context: MacroExpansionContext) throws -> String
    {
        var components: [String] = [declaration.name.text]

        for parent in context.lexicalContext {
            guard let named = parent.asProtocol(NamedDeclSyntax.self) else { continue }
            components.insert(named.name.text, at: 0)
        }

        let sanitizedTableName = try SQLiteHelpers.generateIdentifierName(components)
        return sanitizedTableName
    }
}
